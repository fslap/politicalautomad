namespace Automad\Party\WpColumns;

use Automad\Blocks\AbstractDynamicTemplateBlock;
use Automad\Party\Traits\ComponentConfig;

defined('AUTOMAD') or die('Direct access not permitted!');

/**
 * Party component WpColumns (politicalpartysite → Automad party block).
 *
 * @author Florian Leon Steenbuck
 * @copyright Copyright (c) 2026 by Florian Leon Steenbuck - https://kil.ls
 * @license See LICENSE_PARTY_PURPOSE.md for license information
 */
class WpColumns extends AbstractDynamicTemplateBlock {
	use ComponentConfig;

	public function __construct() {
		parent::__construct(__DIR__, 'wpcolumns');
	}

	public function context(array $config): array {
		return array(
			'left_html' => $config['left_html'],
			'right_html' => $config['right_html'],
			'classes' => $this->getClasses($config)
		);
	}

	protected function definition(): array {
		return array(
			'title' => 'WP Spalten',
			'icon' => 'layout-split',
			'description' => 'Zwei Spalten mit freiem HTML (wp-block-columns).',
			'fields' => array(
				array('name' => 'left_html', 'type' => 'html', 'label' => 'Linke Spalte (HTML)', 'default' => '<p>Links …</p>'),
				array('name' => 'right_html', 'type' => 'html', 'label' => 'Rechte Spalte (HTML)', 'default' => '<p>Rechts …</p>'),
				self::classesField('wp-block-columns')
			)
		);
	}
}
