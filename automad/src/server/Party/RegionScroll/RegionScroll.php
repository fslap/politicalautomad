/**
 * Represents a multi region scroll element that can be used for presenting party locations
 *
 * @author Florian Leon Steenbuck
 * @copyright Copyright (c) 2026 by Florian Leon Steenbuck - https://kil.ls
 * @license See LICENSE_PARTY_PURPOSE.md for license information
 *
 */
class RegionScroll extends AbstractMultiBlock {
    public __construct() {
        parent::__construct(__DIR__, 'regionscroll');
    }

    public function context(array $config): array
    {
         return [
            'section_id' => $config['section_id'] ?? '',
            'navigation_target' => $config['navigation_target'] ?? '',
            'navigation_text' => $config['navigation_text'] ?? '',
            'scroll_width' => $config['scroll_width'] ?? '',
            'regions' => $config['regions'] ?? [],
            'classes' => $this->getClasses(),
            'has_inner_container' => $this->hasInnerContainer()
        ];
    }
}