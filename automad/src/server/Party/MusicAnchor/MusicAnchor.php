use Automad\Blocks\AbstractDynamicTemplateBlock;
use Automad\Party\Traits\ComponentConfig;

defined('AUTOMAD') or die('Direct access not permitted!');

/**
 * Party component MusicAnchor (politicalpartysite → Automad party block).
 *
 * @author Florian Leon Steenbuck
 * @copyright Copyright (c) 2026 by Florian Leon Steenbuck - https://kil.ls
 * @license See LICENSE_PARTY_PURPOSE.md for license information
 */
class MusicAnchor extends AbstractDynamicTemplateBlock {
	use ComponentConfig;

	public function __construct() {
		parent::__construct(__DIR__, 'musicanchor');
	}

	public function context(array $config): array {
		return array(
			'anchor_id' => $config['anchor_id'],
			'classes' => $this->getClasses($config)
		);
	}

	protected function definition(): array {
		return array(
			'title' => 'Musik-Anker',
			'icon' => 'bookmark',
			'description' => 'Unsichtbarer Sprunganker, z.B. für Musik-Links.',
			'fields' => array(
				array('name' => 'anchor_id', 'type' => 'text', 'label' => 'Anker-ID', 'default' => 'music'),
				self::classesField('musicanchor')
			)
		);
	}
}
